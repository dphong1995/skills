// The language is set once by main.js; until then t() reads the page data, so modules that build elements at load (the viewer, the paste box) get the right language whatever the bundle order.
let lang = null;
export const setLang = (l) => { lang = l === 'en' ? 'en' : 'vi'; };
export const t = (key, ...args) => {
  const table = STRINGS[lang || (typeof D !== 'undefined' && D && D.lang === 'en' ? 'en' : 'vi')];
  if (!(key in table)) throw new Error('unknown string key: ' + key);
  const v = table[key];
  return typeof v === 'function' ? v(...args) : v;
};
